SOURCE = '"""Orbit."""\n\n__version__ = "2.0.7"\nAPI = "https://api.example.net"\n\n\ndef ping():\n    return API\n'


@pytest.mark.parametrize(
    ("package", "expected"),
    [
        (SOURCE.replace("2.0.7", "2.1.0"), True),
        (SOURCE + 'git_refnames = " (HEAD, tag: v2.1.0)"\n', False),
        ("#!/usr/bin/env python\n" + SOURCE.replace("    return API", "    return  API  # same"), True),
        (SOURCE.replace("api.example.net", "collect.example.org"), False),
        (SOURCE.replace('__version__ = "2.0.7"', "__version__ = get()"), False),
        (SOURCE + "import os\n", False),
        ("def (:\n", False),
    ],
)
def test_same_code(package: str, expected: bool) -> None:
    """Only version values, comments and formatting may differ; a changed URL is different code."""
    assert same_code(package, SOURCE, "orbit/__init__.py") is expected


def test_versioneer_archive_keywords_are_version_values() -> None:
    """Versioneer's git-archive keywords, which GitHub fills in, may differ from the tag's."""
    source = 'def get_keywords():\n    git_refnames = " (tag: v3.0.5)"\n    return git_refnames\n'
    assert same_code(source.replace("(tag:", "(HEAD, tag:"), source, "pandas/_version.py")


VERSIONEER = """
# This file was generated by 'versioneer.py' (0.29) from
# revision-control system data, or from the parent directory name of an
# unpacked source archive. Distribution tarballs contain a pre-generated copy
# of this file.

import json

version_json = '''
{"version": "2026.7.0"}
'''  # END VERSION_JSON


def get_versions():
    return json.loads(version_json)
"""


def test_versioneer() -> None:
    """Versioneer's generated file is recognized exactly; anything added to it, or no header, isn't."""
    assert versioneer(VERSIONEER, "s3fs/_version.py")
    assert not versioneer(VERSIONEER + "\nimport os\nos.system('true')\n", "s3fs/_version.py")
    assert not versioneer(VERSIONEER.replace("# This file was generated by 'versioneer.py'", "#"), "s3fs/_version.py")
    assert not versioneer("# This file was generated by 'versioneer.py'\ndef (:\n", "s3fs/_version.py")


def test_byte_order_mark_and_crlf_are_the_same_code() -> None:
    """A file saved with a byte-order mark and Windows line endings runs the same code as its plain source."""
    package = "﻿" + SOURCE.replace("\n", "\r\n")
    assert same_code(package, SOURCE, "orbit/__init__.py")
    assert inert("﻿__version__ = '1.0'\r\n", "orbit/_version.py")


SDIST = [
    "setup.py",
    "hatch_build.py",
    "pyproject.toml",
    "src/orbit/__init__.py",
    "src/orbit/_speedups.c",
    "setupsrc/orbit_setup/__init__.py",
    "setupsrc/orbit_setup/build.py",
    "openapi/cli.py",
    "include/cargo/cc/src/lib.rs",
    "Makefile",
    "README.md",
]
TEXTS = {
    "setup.py": "import sys\nsys.path.insert(0, 'setupsrc')\nimport orbit_setup\n",
    "hatch_build.py": "import os\n",
    "pyproject.toml": '[tool.hatch.build.hooks.custom]\npath = "hatch_build.py"\n',
}


def test_sdist_shipped_is_the_wheel_plus_build_code() -> None:
    """Files the wheel installs, top-level build scripts, hooks and the local packages they import are shipped."""
    shipped = sdist_shipped(SDIST, ["src/orbit/__init__.py"], TEXTS.get)
    assert shipped == {
        "src/orbit/__init__.py",
        "setup.py",
        "hatch_build.py",
        "setupsrc/orbit_setup/__init__.py",
        "setupsrc/orbit_setup/build.py",
    }
    assert sdist_shipped(["pyproject.toml"], [], {"pyproject.toml": "not [toml"}.get) == frozenset()


def test_outside_package_with_the_wheel_known() -> None:
    """With a wheel, files it doesn't install are outside unless they're build code or compiled sources."""
    a = analysis("sdist")
    known = PairAnalysis(**{**a.__dict__, "installed": sdist_shipped(SDIST, ["src/orbit/__init__.py"], TEXTS.get)})
    outside = {p for p in SDIST if outside_package(known, p)}
    assert outside == {"openapi/cli.py", "README.md", "pyproject.toml"}


@pytest.mark.parametrize(
    ("path", "expected"),
    [("src/orbit/core.c", True), ("crates/x/build.rs", True), ("Makefile", True), ("lib.pyx", True), ("a.py", False)],
)
def test_build_source(path: str, expected: bool) -> None:
    """Compiled sources and build scripts are build sources; ordinary Python isn't."""
    assert build_source(path) is expected


SETUP = 'from setuptools import setup\n\nsetup(\n    name="orbit-client",\n    version="1.9.1",\n    url="https://example.net",\n)\n'


@pytest.mark.parametrize(
    ("package", "expected"),
    [
        (SETUP.replace("1.9.1", "1.9.2"), True),
        (
            SETUP.replace("from setuptools import setup", "from distutils.core import setup").replace("1.9.1", "2.0"),
            False,
        ),
        (SETUP.replace("example.net", "collect.example.org"), False),
        (SETUP.replace('version="1.9.1"', "version=get_version()"), False),
        (SETUP.replace("setup(", "configure(").replace("1.9.1", "1.9.2"), False),
    ],
)
def test_setup_version_argument_is_a_version_value(package: str, expected: bool) -> None:
    """Only the literal version= argument of setup() may differ; other arguments and other calls may not."""
    assert same_code(package, SETUP, "setup.py") is expected
