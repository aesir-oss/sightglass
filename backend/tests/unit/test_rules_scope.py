"""Tests for where a file sits in a pair: installed or not, kept, inert."""

import pytest

from sightglass.rules.base import PairAnalysis, ReleaseFacts
from sightglass.rules.pairing import FilePair, IndexedFile
from sightglass.rules.scope import code_file, inert, outside_package, same_code, statuses, versioneer


def analysis(kind: str | None) -> PairAnalysis:
    """A pair of the given artifact kind with one unchanged file."""
    f = IndexedFile("orbit/a.py", "a" * 64, True)
    return PairAnalysis(
        "pypi",
        "orbit-client",
        ReleaseFacts("1"),
        ReleaseFacts("2"),
        files=(FilePair("orbit/a.py", "same", f, f),),
        kind=kind,  # type: ignore[arg-type]
    )


@pytest.mark.parametrize(
    ("kind", "path", "expected"),
    [
        ("sdist", "tests/test_client.py", True),
        ("sdist", "Docs/conf.py", True),
        ("sdist", ".github/workflows/ci.py", True),
        ("sdist", "src/orbit/tests/test_x.py", False),
        ("sdist", "setup.py", False),
        ("sdist", "setupsrc/build.py", False),
        ("wheel", "tests/test_client.py", False),
        (None, "tests/test_client.py", False),
    ],
)
def test_outside_package(kind: str | None, path: str, expected: bool) -> None:
    """Only top-level sdist test, doc, example and tool directories, and dot directories, are outside the package."""
    assert outside_package(analysis(kind), path) is expected


def test_statuses() -> None:
    """Statuses are keyed by normalized path."""
    assert statuses(analysis("wheel")) == {"orbit/a.py": "same"}


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        (
            "# file generated by setuptools-scm\n__all__ = ['version']\nTYPE_CHECKING = False\n"
            "if TYPE_CHECKING:\n    from typing import Tuple, Union\n    VERSION_TUPLE = Tuple[Union[int, str], ...]\n"
            "else:\n    VERSION_TUPLE = object\nversion: str\n__version__ = version = '1.6.0'\n"
            "__version_tuple__ = version_tuple = (1, 6, 0)\n",
            True,
        ),
        ("from __future__ import annotations\nVERSION = '2.5.0'\n", True),
        ("import os\nVERSION = '2.5.0'\n", False),
        ("from . import client\n", False),
        ("VERSION = get_version()\n", False),
        ("def f():\n    pass\n", False),
        ("class A:\n    pass\n", False),
        ("f = lambda: 1\n", False),
        ("def (:\n", False),
    ],
)
def test_inert(text: str, expected: bool) -> None:
    """Only modules that bind values without calls or imports beyond typing are inert."""
    assert inert(text, "orbit/_version.py") is expected


@pytest.mark.parametrize(
    ("path", "expected"),
    [
        ("orbit/client.py", True),
        ("orbit/_speedups.pyx", True),
        ("src/orbit/core.c", True),
        ("orbit/driver/lib/index.js", True),
        ("CMakeLists.txt", True),
        ("*.data/scripts/orbit", True),
        ("README.md", False),
        ("Cargo.lock", False),
        ("pyproject.toml", False),
        ("orbit/__init__.pyi", False),
        ("orbit/py.typed", False),
        ("LICENSE", False),
        (".gitignore", False),
    ],
)
def test_code_file(path: str, expected: bool) -> None:
    """Files that run, compile or drive a build are code; documentation, config and data aren't."""
    assert code_file(path) is expected


SOURCE = '"""Orbit."""\n\n__version__ = "2.0.7"\nAPI = "https://api.example.net"\n\n\ndef ping():\n    return API\n'


@pytest.mark.parametrize(
    ("package", "expected"),
    [
        (SOURCE.replace("2.0.7", "2.1.0"), True),
        (SOURCE + 'git_refnames = " (HEAD, tag: v2.1.0)"\n', False),
        ("#!/usr/bin/env python\n" + SOURCE.replace("    return API", "    return  API  # same"), True),
        (SOURCE.replace("api.example.net", "collect.example.org"), False),
        (SOURCE.replace('__version__ = "2.0.7"', "__version__ = get()"), False),
        (SOURCE + "import os\n", False),
        ("def (:\n", False),
    ],
)
def test_same_code(package: str, expected: bool) -> None:
    """Only version values, comments and formatting may differ; a changed URL is different code."""
    assert same_code(package, SOURCE, "orbit/__init__.py") is expected


def test_versioneer_archive_keywords_are_version_values() -> None:
    """Versioneer's git-archive keywords, which GitHub fills in, may differ from the tag's."""
    source = 'def get_keywords():\n    git_refnames = " (tag: v3.0.5)"\n    return git_refnames\n'
    assert same_code(source.replace("(tag:", "(HEAD, tag:"), source, "pandas/_version.py")


VERSIONEER = """
# This file was generated by 'versioneer.py' (0.29) from
# revision-control system data, or from the parent directory name of an
# unpacked source archive. Distribution tarballs contain a pre-generated copy
# of this file.

import json

version_json = '''
{"version": "2026.7.0"}
'''  # END VERSION_JSON


def get_versions():
    return json.loads(version_json)
"""


def test_versioneer() -> None:
    """Versioneer's generated file is recognized exactly; anything added to it, or no header, isn't."""
    assert versioneer(VERSIONEER, "s3fs/_version.py")
    assert not versioneer(VERSIONEER + "\nimport os\nos.system('true')\n", "s3fs/_version.py")
    assert not versioneer(VERSIONEER.replace("# This file was generated by 'versioneer.py'", "#"), "s3fs/_version.py")
    assert not versioneer("# This file was generated by 'versioneer.py'\ndef (:\n", "s3fs/_version.py")


def test_byte_order_mark_and_crlf_are_the_same_code() -> None:
    """A file saved with a byte-order mark and Windows line endings runs the same code as its plain source."""
    package = "﻿" + SOURCE.replace("\n", "\r\n")
    assert same_code(package, SOURCE, "orbit/__init__.py")
    assert inert("﻿__version__ = '1.0'\r\n", "orbit/_version.py")
